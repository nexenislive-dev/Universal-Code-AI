"""Hybrid code generator: local pretrained model first, local knowledge fallback.
No API key or paid inference API is used.
"""
import re
from typing import Dict, Any, Optional
from config import SUPPORTED_LANGUAGES, MAX_TOKENS, DEFAULT_TEMPERATURE
from core.local_model import LocalModel
from core.module_manager import ModuleManager
from utils.helpers import clean_code, extract_code_blocks, detect_language

SYSTEM_PROMPT = """You are a careful senior software engineer. Follow the user's requirements.
For projects with multiple files, output each file as: ```file:path/to/name.ext
...```.
Do not claim code was tested unless it was actually executed. Explain assumptions and dependencies.
Prefer complete, runnable code, input validation, error handling and maintainable structure."""

class CodeGenerator:
    def __init__(self, db, bot=None, independent=None, trainer=None, local_model=None):
        self.db = db
        self.local_model = local_model or LocalModel()
        self.modules = ModuleManager(db)

    def generate(self, request: str, language: Optional[str] = None, save: bool = True, score: float = 0.45) -> Dict[str, Any]:
        language = (language or self._detect_lang(request)).lower().strip()
        docs = self.db.search_documents(request, limit=4) if self.modules.online_enabled() else []
        doc_context = "\n\nREFERENCE NOTES (untrusted; verify before use):\n" + "\n".join(
            f"Source: {d['source_url']}\n{d['content'][:1800]}" for d in docs
        ) if docs else ""
        prompt = f"Target language: {language}\nUser request:\n{request}\n{doc_context}\n\nReturn complete code. If this is an application or multi-file project, include every required file using the exact marker ```file:relative/path.ext followed by its contents and closing triple backticks. Include README and dependency manifest where appropriate. Do not omit essential files."

        result = self.local_model.generate(prompt, system=SYSTEM_PROMPT, temperature=DEFAULT_TEMPERATURE, max_tokens=MAX_TOKENS)
        if result.get("success"):
            content = result["content"]
            blocks = extract_code_blocks(content)
            knowledge_ids = []
            if save:
                for block in blocks:
                    if len(block) >= 40:
                        kid = self.db.add(language=language, code=clean_code(block), title=request[:180],
                            description="Generated by local pretrained model; not automatically verified.",
                            tags=["generated", "unverified"], category="generated", source="local_model",
                            score=0.45, complexity="hard" if len(block) > 1500 else "medium")
                        if kid:
                            knowledge_ids.append(kid)
            return {"success": True, "content": content, "cleaned_code": "\n\n".join(blocks),
                    "mode": "local_model", "language": language, "knowledge_ids": knowledge_ids,
                    "reference_documents": len(docs), "verified": False}

        # No model running: be explicit that examples are retrieval, not generation.
        examples = self.db.search(query=request[:160], language=language, limit=4, min_score=0.6)
        if not examples:
            examples = self.db.search(query=request[:100], limit=3, min_score=0.6)
        if examples:
            text = ["LOCAL MODEL NOT RUNNING. These are retrieved examples, NOT newly generated code."]
            for item in examples:
                text.append(f"\n[{item['language']}] {item.get('title','')}\n```{item['language']}\n{item['code']}\n```")
            return {"success": True, "content": "\n".join(text), "mode": "retrieval_fallback", "language": language,
                    "examples_used": len(examples), "model_error": result.get("error")}
        return {"success": False, "content": "Local coding model is not running and no matching verified examples were found. Start llama.cpp server with a downloaded GGUF coding model, then try again.",
                "mode": "model_unavailable", "language": language, "model_error": result.get("error")}

    def learn_url(self, url: str, topic: str = "", language: str = "general"):
        if not self.modules.online_enabled():
            return {"success": False, "error": "Online learning is disabled"}
        from core.online_learning import OnlineLearning
        return OnlineLearning(self.db).learn_url(url, topic, language)

    @staticmethod
    def _detect_lang(text: str) -> str:
        text_l = text.lower()
        aliases = {"c++": "cpp", "c#": "csharp", "js": "javascript", "ts": "typescript", "py": "python", "golang": "go"}
        for alias, lang in aliases.items():
            if alias in text_l:
                return lang
        for lang in SUPPORTED_LANGUAGES:
            if re.search(rf"\b{re.escape(lang)}\b", text_l):
                return lang
        if any(x in text_l for x in ("website", "webpage", "frontend")):
            return "html"
        if any(x in text_l for x in ("android", "mobile app")):
            return "kotlin"
        return "python"
